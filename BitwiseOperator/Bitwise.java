package BitwiseOperator;

public class Bitwise {
    public static void main(String[] args) {

        int a = 5;
        int b = 10;
        int c = 100;
        System.out.println(a & b);
        System.out.println(a | b);
        System.out.println(a ^ b);
        System.out.println(3 << 2);
        System.out.println(b >> 2);
        System.out.println(c >> 3);
    }
}
